const normalizeCityKey = (value) =>
  value
    .replace(/[^a-z0-9\s-]/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();

const buildCityPhotoUrl = (query) => `https://loremflickr.com/800/600/${encodeURIComponent(`${query} city travel`)}`;

const generatedCityImages = generatedPhotoCityQueries.reduce((images, query) => {
  const cityName = query.split(',')[0];
  images[normalizeCityKey(cityName)] = buildCityPhotoUrl(query);
  return images;
}, {});

const cityImages = {
  ...generatedCityImages,
  ...curatedCityImages
};

const cityImageKeys = Object.keys(cityImages).sort((a, b) => b.length - a.length);
const liveCityImageCache = {};
const liveCityImageRequests = {};
const WIKIPEDIA_THUMB_SIZE = '800';

const getCandidateWikipediaTitles = (location) => {
  const trimmed = location.trim();
  const cityOnly = trimmed.split(',')[0]?.trim();
  return [...new Set([trimmed, cityOnly].filter(Boolean))];
};

async function fetchWikipediaCityImageUrl(location) {
  const titles = getCandidateWikipediaTitles(location);

  for (const title of titles) {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 2500);

    try {
      const params = new URLSearchParams({
        action: 'query',
        format: 'json',
        origin: '*',
        redirects: '1',
        prop: 'pageimages',
        piprop: 'thumbnail',
        pithumbsize: WIKIPEDIA_THUMB_SIZE,
        titles: title
      });
      const response = await fetch(`https://en.wikipedia.org/w/api.php?${params.toString()}`, {
        signal: controller.signal
      });
      const data = await response.json();
      const pages = Object.values(data?.query?.pages ?? {});
      const pageWithImage = pages.find((page) => page?.thumbnail?.source);
      const imageUrl = pageWithImage?.thumbnail?.source;

      if (imageUrl && !imageUrl.endsWith('.svg')) {
        return imageUrl;
      }
    } catch (error) {
      return null;
    } finally {
      clearTimeout(timeoutId);
    }
  }

  return null;
}

async function fetchWikipediaCityImageUrls(locations) {
  const locationTitles = locations.reduce((entries, location) => {
    entries[location] = getCandidateWikipediaTitles(location);
    return entries;
  }, {});
  const titles = [...new Set(Object.values(locationTitles).flat())];
  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), 3500);

  try {
    const params = new URLSearchParams({
      action: 'query',
      format: 'json',
      origin: '*',
      redirects: '1',
      prop: 'pageimages',
      piprop: 'thumbnail',
      pithumbsize: WIKIPEDIA_THUMB_SIZE,
      titles: titles.join('|')
    });
    const response = await fetch(`https://en.wikipedia.org/w/api.php?${params.toString()}`, {
      signal: controller.signal
    });
    const data = await response.json();
    const redirects = (data?.query?.redirects ?? []).reduce((map, redirect) => {
      map[normalizeCityKey(redirect.from)] = normalizeCityKey(redirect.to);
      return map;
    }, {});
    const imagesByTitle = Object.values(data?.query?.pages ?? {}).reduce((images, page) => {
      if (page?.title && page?.thumbnail?.source && !page.thumbnail.source.endsWith('.svg')) {
        images[normalizeCityKey(page.title)] = page.thumbnail.source;
      }
      return images;
    }, {});

    return locations.reduce((images, location) => {
      const imageUrl = locationTitles[location]
        .map((title) => normalizeCityKey(title))
        .map((title) => imagesByTitle[redirects[title] || title])
        .find(Boolean);
      if (imageUrl) {
        images[location] = imageUrl;
      }
      return images;
    }, {});
  } catch (error) {
    return {};
  } finally {
    clearTimeout(timeoutId);
  }
}

function getFallbackBoardImageUrl(location) {
  const normalizedLocation = normalizeCityKey(location);
  const cityKey = cityImageKeys.find((city) => normalizedLocation.includes(city));

  if (cityKey) {
    return cityImages[cityKey];
  }

  return buildCityPhotoUrl(location);
}

export async function getBoardImageUrl(location) {
  if (liveCityImageCache[location]) {
    return liveCityImageCache[location];
  }
  if (liveCityImageRequests[location]) {
    return liveCityImageRequests[location];
  }

  liveCityImageRequests[location] = fetchWikipediaCityImageUrl(location).then((wikipediaImageUrl) => {
    const imageUrl = wikipediaImageUrl || getFallbackBoardImageUrl(location);
    liveCityImageCache[location] = imageUrl;
    delete liveCityImageRequests[location];
    return imageUrl;
  });

  return liveCityImageRequests[location];
}

export async function hydrateTripImages(trips) {
  const locations = [...new Set(trips.map((trip) => trip.location || trip.title).filter(Boolean))];
  const uncachedLocations = locations.filter((location) => !liveCityImageCache[location]);
  const wikipediaImagesByLocation = uncachedLocations.length
    ? await fetchWikipediaCityImageUrls(uncachedLocations)
    : {};

  uncachedLocations.forEach((location) => {
    liveCityImageCache[location] = wikipediaImagesByLocation[location] || getFallbackBoardImageUrl(location);
  });

  return trips.map((trip) => {
    const location = trip.location || trip.title;
    return {
      ...trip,
      image: liveCityImageCache[location] || getFallbackBoardImageUrl(location)
    };
  });
}

